/**
 * AMARACUS Cryptographic Infrastructure — AI / Machine Learning Boundary
 *
 * SECTION 35 MANDATE:
 * AI / ML models MUST NOT directly authorize security-critical cryptographic operations.
 *
 * Authoritative security enforcement is 100% deterministic, testable, and auditable.
 * AI assistance is strictly confined to:
 *  - Explaining policy decisions and violations to humans.
 *  - Summarizing cryptographic posture and CBOM findings.
 *  - Generating draft policy configurations for human review and explicit activation.
 */

import { PolicyDecision, PolicyDocument, PolicyEvaluationContext } from './types';

export interface AiExplanationResult {
  summary: string;
  securityImpact: string;
  recommendedActions: string[];
  disclaimer: string;
}

export class CryptographicAiBoundary {
  private static readonly DISCLAIMER =
    'AI-generated explanation only. Authorization is determined strictly by the deterministic AMARACUS Cryptographic Policy Engine.';

  /**
   * Asserts that an authorization decision was generated by the deterministic engine,
   * completely preventing unauthorized synthetic decision injection.
   */
  public static assertDeterministicAuthority(decision: PolicyDecision): void {
    if (!decision || typeof decision.allowed !== 'boolean' || !decision.policyVersion) {
      throw new Error(
        'AUTHORIZATION_REJECTED: Malformed or unverified decision structure. Execution requires deterministic engine evaluation.'
      );
    }
  }

  /**
   * Generates safe, human-readable explanations of complex policy outcomes.
   */
  public static explainDecision(decision: PolicyDecision): AiExplanationResult {
    let summary: string;
    let securityImpact: string;

    if (decision.decision === 'ALLOW') {
      summary = 'Operation complies with all mandatory organizational and global cryptographic baselines.';
      securityImpact = 'Zero policy violations detected. Cryptographic primitives meet required security thresholds.';
    } else if (decision.decision === 'REQUIRE_KEY_ROTATION') {
      summary = 'Operation halted because the selected key has exceeded configured maximum lifetime or operation limits.';
      securityImpact = 'Using aging cryptographic keys elevates susceptibility to cryptanalysis and key compromise.';
    } else if (decision.decision === 'REQUIRE_STRONGER_ALGORITHM') {
      summary = 'Operation halted because policy mandates stronger or quantum-safe cryptographic algorithms.';
      securityImpact = 'Classical algorithms do not meet the security posture mandated by this policy profile.';
    } else if (decision.decision === 'REQUIRE_APPROVED_PROVIDER') {
      summary = 'Operation halted because policy requires an HSM or dedicated customer-managed vault provider.';
      securityImpact = 'Software-only execution is prohibited by enterprise compliance mandates.';
    } else {
      summary = `Operation DENIED due to policy violations: ${decision.reasons.join(', ')}`;
      securityImpact = 'The requested parameters do not satisfy mandatory security or compliance constraints.';
    }

    const recommendedActions =
      decision.recommendations.length > 0
        ? decision.recommendations
        : decision.requirements.length > 0
        ? decision.requirements
        : decision.reasons.length > 0
        ? decision.reasons
        : ['Ensure operations follow corporate cryptographic guidelines.'];

    return {
      summary,
      securityImpact,
      recommendedActions,
      disclaimer: this.DISCLAIMER,
    };
  }
}

export { CryptographicAiBoundary as PolicyAiBoundary };

